// Generates the Fabric notebook that loads input Excel files from the Lakehouse folder
// gitsit_files/Files/input into Input_table, one File_Name per file (the Excel file's name).
//
//   node scripts/gen-loader.ts
//
// Writes docs/input-loader.ipynb. The notebook reads the files with the same rules as
// scripts/gen-store.ts read the original input tape, so a file loads exactly as that one did.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { INPUT_COLUMNS } from '../src/store/generated/store-fields.ts';
import { TABLE_TYPE } from '../src/store/generated/lookup-fields.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');

const SERVER = 'wssfdnev5nyelmdvw3xumqun3i-pqhpudri7sjejflsu6qgtrtzvm.database.fabric.microsoft.com';
const DATABASE = 'gitsit-test-e40f6906-4431-48db-8eca-33c1fd246d16';

const columns = INPUT_COLUMNS.map((c) => [c.header, c.name, c.type]);

const code = `# Loads every new or changed Excel file in this Lakehouse's Files/input folder into Input_table
# (database gitsit-test). Each file's rows get File_Name = the file's name without ".xlsx", e.g.
# "Jet Lending - 2025.09 - $97mm". A file loaded again replaces that file's earlier rows.
# A loaded file is moved to Files/Archive as "<load time> - <file name>". Run by the pipeline
# "Load input files on upload" as soon as a file lands in Files/input, and hourly as a fallback.
# Generated by packages/frontend/scripts/gen-loader.ts - edit there, not here.

import datetime, json, os, re, struct
import pandas as pd
import pyodbc

SERVER = "${SERVER}"
DATABASE = "${DATABASE}"
FOLDER = "/lakehouse/default/Files/input"
ARCHIVE = "Files/Archive"
TABLE_TYPE = "${TABLE_TYPE}"
TEXT_MAX = 400
# Input_table columns: [Excel header, column, type]; the first column is always loan_id.
COLUMNS = json.loads(r'''${JSON.stringify(columns)}''')

def connect():
    token = notebookutils.credentials.getToken("https://database.windows.net/").encode("UTF-16-LE")
    attrs = {1256: struct.pack(f"<I{len(token)}s", len(token), token)}  # SQL_COPT_SS_ACCESS_TOKEN
    return pyodbc.connect(f"Driver={{ODBC Driver 18 for SQL Server}};Server={SERVER},1433;Database={DATABASE};Encrypt=yes;", attrs_before=attrs)

def empty(v):
    return v is None or (isinstance(v, str) and v == "") or (not isinstance(v, str) and pd.isna(v))

def value(v, name, kind):
    """A cell as Input_table stores it (the same rules as the original load)."""
    if empty(v):
        return None
    if isinstance(v, pd.Timestamp):
        v = v.to_pydatetime()
    if kind == "date":
        return v if isinstance(v, datetime.datetime) else None
    if kind == "decimal":
        try:
            return float(v)
        except (TypeError, ValueError):
            return None
    if isinstance(v, datetime.datetime):
        # Excel reads the delinquency bucket "1-30" as January 1930; keep the text people typed.
        return f"{v.month}-{str(v.year)[2:]}" if name == "seller_status" else v.strftime("%Y-%m-%d")
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return str(v)[:TEXT_MAX]

def read_file(path):
    df = pd.read_excel(path, sheet_name=0, header=0, dtype=object)
    headers = [re.sub(r"\\s+", " ", str(h)).strip().lower() for h in df.columns]
    index = {h: i for i, h in enumerate(headers)}
    missing = [h for h, _, _ in COLUMNS[1:] if h.lower() not in index]
    rows = []
    for rec in df.itertuples(index=False):
        if empty(rec[0]):
            continue
        row = [value(rec[0], "loan_id", "text")]
        for header, name, kind in COLUMNS[1:]:
            i = index.get(header.lower())
            row.append(value(rec[i], name, kind) if i is not None else None)
        rows.append(row)
    return rows, missing

conn = connect()
cur = conn.cursor()
cur.execute("""IF OBJECT_ID('dbo.Input_files') IS NULL
CREATE TABLE dbo.Input_files (File_Name NVARCHAR(200) NOT NULL PRIMARY KEY, File_Modified DATETIME2 NOT NULL,
  Loans INT NOT NULL, Missing_Columns NVARCHAR(4000) NULL, Loaded_On DATETIME2 NOT NULL)""")
conn.commit()
loaded = {r[0]: r[1] for r in cur.execute("SELECT File_Name, File_Modified FROM dbo.Input_files").fetchall()}

names = ["Table_Type", "File_Name"] + [name for _, name, _ in COLUMNS]
insert = f"INSERT INTO dbo.Input_table ({', '.join('[' + n + ']' for n in names)}) VALUES ({', '.join('?' for _ in names)})"
cur.fast_executemany = True
results = []
os.makedirs(FOLDER, exist_ok=True)
for f in sorted(os.listdir(FOLDER)):
    path = os.path.join(FOLDER, f)
    if f.startswith("~$") or not f.lower().endswith((".xlsx", ".xlsm")) or not os.path.isfile(path):
        continue
    file_name = os.path.splitext(f)[0].strip()[:200]
    modified = datetime.datetime.utcfromtimestamp(os.path.getmtime(path)).replace(microsecond=0)
    if loaded.get(file_name) == modified:
        note = "already loaded"  # loaded before archiving existed: just archive it
    else:
        rows, missing = read_file(path)
        try:
            cur.execute("DELETE FROM dbo.Input_table WHERE File_Name = ?", file_name)
            if rows:
                cur.executemany(insert, [[TABLE_TYPE, file_name] + r for r in rows])
            cur.execute("DELETE FROM dbo.Input_files WHERE File_Name = ?", file_name)
            cur.execute("INSERT INTO dbo.Input_files VALUES (?, ?, ?, ?, SYSUTCDATETIME())",
                        file_name, modified, len(rows), ", ".join(missing) or None)
            conn.commit()
        except Exception as e:
            conn.rollback()
            results.append(f"{file_name}: FAILED - {e}")
            continue
        note = f"{len(rows)} loans" + (f" (missing columns: {', '.join(missing)})" if missing else "")
    # Loaded: move the file to Files/Archive, its name prefixed with the load time so earlier
    # versions of the same file are kept. A file that failed stays in Files/input.
    stamp = datetime.datetime.utcnow().strftime("%Y-%m-%d %H%M%S")
    archived = f"{ARCHIVE}/{stamp} - {f}"
    try:
        notebookutils.fs.mv(f"Files/input/{f}", archived, True)
    except Exception as e:
        archived = f"not archived ({e})"
    results.append(f"{file_name}: {note}; file moved to {archived}")
conn.close()
print("\\n".join(results) or "No new or changed files.")
if any("FAILED" in r for r in results):
    raise Exception("\\n".join(r for r in results if "FAILED" in r))
`;

