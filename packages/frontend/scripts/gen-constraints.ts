// Generates the Constraints tables people and the app set the model constants in, per input file,
// and the defaults every file starts from (first filled with the Model sheet's own values).
//
//   node scripts/gen-constraints.ts
//
// Reads data/Pacific Private Money - model.xlsx and src/engine/constraint-fields.ts. Writes:
//   src/engine/generated/constraint-defaults.json   (Field_Index -> the Model sheet's value)
//   docs/constraints.sql                            (schema, tables, defaults; safe to rerun)
//
// How the pieces fit: Constraints.ConstraintDefaults holds one default per field. When the loader
// lists a new input file (NPL or BPL) in dbo.Input_files, a trigger copies every default into
// Constraints.ConstraintValues for that file, one row per file and field; the Constraints page then
// changes that file's rows only, and Constraints.ConstraintChanges logs every value it applies. A
// default changed later reaches the files uploaded after it, not the ones already loaded. The app's
// data service only reaches dbo tables, so the app reads and writes these through its functions
// (packages/functions), which run SQL.

import ExcelJS from 'exceljs';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CONSTRAINT_FIELDS, constraintText } from '../src/engine/constraint-fields.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const SCHEMA = 'Constraints';
const DEFAULTS = `[${SCHEMA}].[ConstraintDefaults]`;
const VALUES = `[${SCHEMA}].[ConstraintValues]`;
const CHANGES = `[${SCHEMA}].[ConstraintChanges]`;
/** The tables' names before the BPL_ prefix was dropped (they hold rows for NPL files too). */
const RENAMED = [['BPL_ConstraintDefaults', 'ConstraintDefaults'], ['BPL_ConstraintValues', 'ConstraintValues'], ['BPL_ConstraintChanges', 'ConstraintChanges']];
const RENAMED_KEYS = [['PK_BPL_ConstraintDefaults', 'PK_ConstraintDefaults'], ['PK_BPL_ConstraintValues', 'PK_ConstraintValues'], ['DF_BPL_ConstraintChanges_Changed_On', 'DF_ConstraintChanges_Changed_On']];
const INPUT = 'dbo.[InputLoans]';
const EXCEL_EPOCH = Date.UTC(1899, 11, 30);

const sql = (s: string) => `N'${s.replace(/'/g, "''")}'`;

async function main() {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(resolve(root, 'data/Pacific Private Money - model.xlsx'));
  const ws = wb.getWorksheet('Model')!;

  const defaults: Record<string, string> = {};
  for (const f of CONSTRAINT_FIELDS) {
    let v: unknown = f.literal ? f.literal.value : ws.getCell(f.cell).value;
    if (v && typeof v === 'object' && 'result' in v) v = v.result;
    if (v instanceof Date) v = (v.getTime() - EXCEL_EPOCH) / 864e5;
    if (typeof v !== 'number') throw new Error(`Model!${f.cell} (${f.index}) has no number: ${JSON.stringify(v)}`);
    defaults[f.index] = constraintText(f, v);
  }
  writeFileSync(resolve(here, '../src/engine/generated/constraint-defaults.json'), `${JSON.stringify(defaults, null, 2)}\n`);

  const cols = '[File_Name], [Field_Index], [Field_Name_Display], [Value]';
  /** Rows for the given files (a query with a File_Name column) and the fields they have no row for. */
  const fillDefaults = (files: string) => `INSERT INTO ${VALUES} (${cols})
  SELECT f.[File_Name], d.[Field_Index], d.[Field_Name_Display], d.[Value]
  FROM (${files}) AS f CROSS JOIN ${DEFAULTS} AS d
  WHERE NOT EXISTS (SELECT 1 FROM ${VALUES} AS c WHERE c.[File_Name] = f.[File_Name] AND c.[Field_Index] = d.[Field_Index]);`;

  writeFileSync(resolve(root, 'docs/constraints.sql'), `-- The model constants per input file, in their own schema (folder) ${SCHEMA}:
--   ${DEFAULTS}: one default per Field_Index; every new input file (NPL or BPL) starts with these.
--     Edit a Value here to change it for the files uploaded from then on.
--   ${VALUES}: one row per File_Name and Field_Index, filled from the defaults when the
--     loader lists the file in dbo.Input_files; the app's Constraints page changes a file's rows.
--     (Percentages as fractions, 0.7 = 70%; dates as yyyy-mm-dd.)
--   ${CHANGES}: every value the app's Constraints page applied (who, when, old and new).
-- The app reads and writes them through its functions. Safe to rerun: it keeps every value.
-- Generated by packages/frontend/scripts/gen-constraints.ts.

SET XACT_ABORT ON;
IF SCHEMA_ID('${SCHEMA}') IS NULL EXEC('CREATE SCHEMA [${SCHEMA}] AUTHORIZATION [dbo]');
GO
-- The tables were called BPL_ConstraintDefaults etc.; renamed in place, with their rows.
${RENAMED.map(([from, to]) => `IF OBJECT_ID('[${SCHEMA}].[${from}]', 'U') IS NOT NULL AND OBJECT_ID('[${SCHEMA}].[${to}]', 'U') IS NULL
  EXEC sp_rename N'[${SCHEMA}].[${from}]', N'${to}';`).join('\n')}
${RENAMED_KEYS.map(([from, to]) => `IF OBJECT_ID('[${SCHEMA}].[${from}]') IS NOT NULL
  EXEC sp_rename N'[${SCHEMA}].[${from}]', N'${to}', N'OBJECT';`).join('\n')}
GO
IF OBJECT_ID('${DEFAULTS}', 'U') IS NULL
  CREATE TABLE ${DEFAULTS} (
    [Field_Index] NVARCHAR(100) NOT NULL,
    [Field_Name_Display] NVARCHAR(200) NOT NULL,
    [Value] NVARCHAR(100) NULL,
    CONSTRAINT [PK_ConstraintDefaults] PRIMARY KEY ([Field_Index])
  );
IF OBJECT_ID('${VALUES}', 'U') IS NULL
  CREATE TABLE ${VALUES} (
    [File_Name] NVARCHAR(200) NOT NULL,
    [Field_Index] NVARCHAR(100) NOT NULL,
    [Field_Name_Display] NVARCHAR(200) NOT NULL,
    [Value] NVARCHAR(100) NULL,
    CONSTRAINT [PK_ConstraintValues] PRIMARY KEY ([File_Name], [Field_Index])
  );
IF OBJECT_ID('${CHANGES}', 'U') IS NULL
  CREATE TABLE ${CHANGES} (
    [File_Name] NVARCHAR(200) NOT NULL,
    [Field_Index] NVARCHAR(100) NOT NULL,
    [Field_Name_Display] NVARCHAR(200) NOT NULL,
    [Old_Value] NVARCHAR(100) NULL,
    [New_Value] NVARCHAR(100) NULL,
    [User_mail] NVARCHAR(200) NOT NULL,
    [Changed_On] DATETIME2 NOT NULL CONSTRAINT [DF_ConstraintChanges_Changed_On] DEFAULT SYSUTCDATETIME()
  );
GO
-- The Model sheet's values, for the fields that have no default yet (a default edited here stays).
INSERT INTO ${DEFAULTS} ([Field_Index], [Field_Name_Display], [Value])
SELECT d.[Field_Index], d.[Field_Name_Display], d.[Value] FROM (VALUES
${CONSTRAINT_FIELDS.map((f) => `  (${sql(f.index)}, ${sql(f.display)}, ${sql(defaults[f.index])})`).join(',\n')}
) AS d ([Field_Index], [Field_Name_Display], [Value])
WHERE NOT EXISTS (SELECT 1 FROM ${DEFAULTS} AS c WHERE c.[Field_Index] = d.[Field_Index]);
GO
-- Input files the loader adds later start with the defaults.
IF OBJECT_ID('dbo.[Input_files]', 'U') IS NOT NULL
  EXEC('CREATE OR ALTER TRIGGER dbo.[trg_Input_files_constraints] ON dbo.[Input_files] AFTER INSERT AS
BEGIN
  SET NOCOUNT ON;
  ${fillDefaults('SELECT DISTINCT [File_Name] FROM inserted').replace(/'/g, "''")}
END');
GO
-- The input files loaded so far (and any field added since a file was filled).
${fillDefaults(`SELECT DISTINCT [File_Name] FROM ${INPUT}`).replace(/^ {2}/gm, '')}
GO
`);
  console.log(`${CONSTRAINT_FIELDS.length} constraint fields; defaults written`);
}

await main();
